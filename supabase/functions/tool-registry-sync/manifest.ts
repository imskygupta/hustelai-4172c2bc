export function manifestHash(t: ToolEntry): string {
  const s = JSON.stringify({
    n: t.name, d: t.description, c: t.category, t: t.tier,
    w: t.workflows_supported, k: t.keywords, r: t.related_tools,
    f: t.feature_summary, s: t.seo_keywords, u: t.ideal_use_case,
    g: t.conversion_goal, cta: t.internal_cta, url: t.internal_url,
    p: t.premium_only,
  });
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(16);
}