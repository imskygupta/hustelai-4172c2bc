const heroQuotaReached = `# Quota reached

You'll see a **"Quota reached"** message when you've hit a daily or
monthly cap. Here's what's happening and how to keep working.

## What just happened

HustleAI tracks a few operational counters per plan:

- **AI tool runs** (daily)
- **Exports** (monthly)
- **Resend attempts** (per export)
- **Active roadmaps** (concurrent)

When one hits its cap, new work in that area pauses. Everything you've
already generated stays available.

## What still works

- Opening, downloading, and sharing existing exports.
- Reading and editing existing roadmaps.
- Browsing your continuity rail and search history.
- Receiving previously-delivered Telegram artifacts.

## How to unblock

1. **Wait for reset.** Daily counters reset at midnight UTC; monthly counters reset on your billing anniversary.
2. **Upgrade your plan.** Pro / Elite / Infinity dramatically raise or remove the cap. See [Pricing & Plans](/pricing-overview).
3. **Free up a roadmap slot** (if you hit the active roadmap cap) by archiving completed roadmaps.

## Why the cap exists

Caps keep generation cost predictable for you and keep delivery fast
for everyone. Higher tiers come with priority execution, so heavy
users don't slow down anyone else.

## Still stuck?

If the counter looks wrong — for example, you haven't generated
anything but the cap shows full — see [Missing export](/missing-export)
and contact support from the workspace footer.
`;

