const heroFirstExport = `# Your first export

An **export** is any finished artifact HustleAI produces — a PDF
roadmap, a proposal, a document, a resume, a workflow result.
Exports are saved to your workspace and (when configured) delivered
to your connected channels.

## How exports work

1. You generate something — a roadmap, a proposal, a document.
2. HustleAI packages it as an export with a title, a preview, and a download link.
3. The export appears in your **Exports** panel immediately.
4. If Telegram delivery is connected, a copy is pushed there too.

## What you can do with an export

- **Open** — view the rendered artifact in the workspace.
- **Download** — save a local copy (PDF, DOCX, or the artifact's native format).
- **Share** — generate a shareable link.
- **Resend** — re-deliver to Telegram if you cleared the original message.
- **Reopen** — return to the source workspace where the export was generated.

## Where exports live

- Inside your workspace under **Exports**, sorted newest first.
- Mirrored to your Telegram (if connected) for offline access and easy phone retrieval.
- Indexed by your workspace continuity so search and roadmaps can reference them.

## Lifecycle

Exports stay available based on your plan's continuity window. After
the window, the artifact enters a **degraded** state — the record stays
visible, but Open / Share / Resend are paused until you upgrade or
re-generate. The Telegram copy (if delivered) remains permanently in
your chat history. See [Continuity lifecycle](/continuity-lifecycle).

Next: [Connect Telegram for instant delivery](/telegram-connection)
`;

