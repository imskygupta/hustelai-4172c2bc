import { supabase } from "@/integrations/supabase/client";
import { marked } from "marked";

interface RoadmapRow {
  id: string;
  hustle_title: string;
  hustle_category: string;
  hustle_earnings: string;
  hustle_type: string;
  hustle_startup_cost?: string;
  content: string;
  created_at: string;
}

/**
 * Opens a fully-styled, print/PDF-ready roadmap view in a new tab.
 * Uses the same branded layout as the in-app viewer, but as a clean
 * standalone page (no app chrome) — better UX than navigating in-app.
 */
export async function openRoadmapPrint(idOrRow: string | RoadmapRow, autoPrint = false) {
  let roadmap: RoadmapRow | null = null;
  if (typeof idOrRow === "string") {
    const { data } = await supabase
      .from("hustle_roadmaps")
      .select("*")
      .eq("id", idOrRow)
      .single();
    roadmap = data as RoadmapRow;
  } else {
    roadmap = idOrRow;
  }
  if (!roadmap) return;

  const win = window.open("", "_blank");
  if (!win) return;

  const html = marked.parse(roadmap.content || "") as string;

  win.document.write(`<!DOCTYPE html><html><head>
    <meta charset="utf-8" />
    <title>${roadmap.hustle_title} — HustleAI Roadmap</title>
    <style>
      @import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Space+Grotesk:wght@500;600;700&display=swap');
      *{margin:0;padding:0;box-sizing:border-box}
      body{font-family:'Inter',sans-serif;padding:48px;color:#1a1a2e;background:#fff;position:relative;max-width:900px;margin:0 auto}
      h1{font-family:'Space Grotesk',sans-serif;font-size:32px;margin-bottom:8px;color:#0d9488}
      h2{font-family:'Space Grotesk',sans-serif;font-size:22px;margin:32px 0 12px;color:#0f766e;border-bottom:2px solid #ccfbf1;padding-bottom:8px}
      h3{font-size:17px;margin:20px 0 8px;color:#1a1a2e;font-weight:600}
      p{margin:10px 0;line-height:1.7;font-size:14px}
      ul,ol{margin:10px 0 10px 28px}
      li{margin:6px 0;line-height:1.65;font-size:14px}
      code{background:#f0fdfa;padding:2px 6px;border-radius:4px;font-size:13px;color:#0d9488}
      pre{background:#f0fdfa;padding:16px;border-radius:8px;overflow-x:auto;margin:12px 0;border:1px solid #ccfbf1}
      strong{color:#0f172a}
      a{color:#0d9488}
      .watermark{position:fixed;top:50%;left:50%;transform:translate(-50%,-50%) rotate(-30deg);font-size:90px;font-weight:bold;color:rgba(13,148,136,.04);white-space:nowrap;pointer-events:none;z-index:0;font-family:'Space Grotesk',sans-serif}
      .header{border-bottom:3px solid #0d9488;padding-bottom:20px;margin-bottom:32px;position:relative;z-index:1}
      .subtitle{color:#64748b;font-size:13px;margin-top:6px}
      .meta{display:flex;gap:10px;margin-top:14px;font-size:12px;color:#64748b;flex-wrap:wrap}
      .meta span{background:#f0fdfa;padding:4px 10px;border-radius:999px;border:1px solid #ccfbf1}
      .content{position:relative;z-index:1}
      .footer{margin-top:48px;border-top:2px solid #e2e8f0;padding-top:20px;text-align:center;color:#94a3b8;font-size:11px;position:relative;z-index:1}
      .actions{position:fixed;top:16px;right:16px;display:flex;gap:8px;z-index:10}
      .actions button{background:#0d9488;color:white;border:none;padding:8px 16px;border-radius:8px;font-family:inherit;font-size:13px;font-weight:600;cursor:pointer;box-shadow:0 2px 8px rgba(13,148,136,.3)}
      .actions button:hover{background:#0f766e}
      @media print{.actions{display:none}.watermark{position:fixed}body{padding:32px;max-width:none}}
    </style></head><body>
      <div class="actions"><button onclick="window.print()">⬇ Download PDF</button></div>
      <div class="watermark">⚡ HustleAI</div>
      <div class="header">
        <h1>⚡ ${roadmap.hustle_title}</h1>
        <div class="subtitle">AI-Generated Roadmap by HustleAI — Your Side Hustle Blueprint</div>
        <div class="meta">
          <span>📂 ${roadmap.hustle_category}</span>
          <span>💰 ${roadmap.hustle_earnings}</span>
          <span>🏷️ ${roadmap.hustle_type}</span>
          <span>📅 ${new Date(roadmap.created_at).toLocaleDateString()}</span>
        </div>
      </div>
      <div class="content">${html}</div>
      <div class="footer">
        <p>Generated by <a href="https://hustlaiapp.in">HustleAI</a> — AI-Powered Side Hustle Discovery Platform</p>
        <p style="margin-top:4px;">© ${new Date().getFullYear()} HustleAI — hustlaiapp.in</p>
      </div>
    </body></html>`);
  win.document.close();
  if (autoPrint) setTimeout(() => win.print(), 800);
}