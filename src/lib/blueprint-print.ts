import { marked } from "marked";

interface BlueprintInput {
  title: string;
  description?: string;
  actionScore?: number;
  content: string; // markdown
}

/**
 * Open a fully-styled, print/PDF-ready Blueprint view in a NEW TAB.
 * Same pattern as roadmap-print: clean standalone page, branded watermark,
 * native browser "Save as PDF" for tiny file sizes (no html2canvas → no 50MB PDFs).
 */
export function openBlueprintPrint(b: BlueprintInput, autoPrint = false) {
  const win = window.open("", "_blank");
  if (!win) return;
  const html = marked.parse(b.content || "") as string;

  win.document.write(`<!DOCTYPE html><html><head>
    <meta charset="utf-8" />
    <title>${b.title} — HustleAI Blueprint</title>
    <style>
      @import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Space+Grotesk:wght@500;600;700&display=swap');
      *{margin:0;padding:0;box-sizing:border-box}
      body{font-family:'Inter',sans-serif;padding:48px;color:#1a1a2e;background:#fff;position:relative;max-width:900px;margin:0 auto}
      h1{font-family:'Space Grotesk',sans-serif;font-size:32px;margin-bottom:8px;color:#3b82f6}
      h2{font-family:'Space Grotesk',sans-serif;font-size:22px;margin:32px 0 12px;color:#2563eb;border-bottom:2px solid #dbeafe;padding-bottom:8px}
      h3{font-size:17px;margin:20px 0 8px;color:#1a1a2e;font-weight:600}
      p{margin:10px 0;line-height:1.7;font-size:14px}
      ul,ol{margin:10px 0 10px 28px}
      li{margin:6px 0;line-height:1.65;font-size:14px}
      code{background:#eff6ff;padding:2px 6px;border-radius:4px;font-size:13px;color:#2563eb}
      pre{background:#eff6ff;padding:16px;border-radius:8px;overflow-x:auto;margin:12px 0;border:1px solid #dbeafe}
      strong{color:#0f172a}
      a{color:#2563eb}
      .watermark{position:fixed;top:50%;left:50%;transform:translate(-50%,-50%) rotate(-30deg);font-size:90px;font-weight:bold;color:rgba(59,130,246,.05);white-space:nowrap;pointer-events:none;z-index:0;font-family:'Space Grotesk',sans-serif}
      .header{border-bottom:3px solid #3b82f6;padding-bottom:20px;margin-bottom:32px;position:relative;z-index:1}
      .badge{display:inline-flex;align-items:center;gap:6px;background:#eff6ff;color:#2563eb;padding:4px 12px;border-radius:999px;font-size:12px;font-weight:600;border:1px solid #dbeafe;margin-bottom:10px}
      .subtitle{color:#64748b;font-size:13px;margin-top:6px}
      .score{display:inline-block;margin-top:14px;background:#eff6ff;color:#2563eb;font-weight:700;padding:6px 14px;border-radius:8px;font-size:14px}
      .content{position:relative;z-index:1}
      .footer{margin-top:48px;border-top:2px solid #e2e8f0;padding-top:20px;text-align:center;color:#94a3b8;font-size:11px;position:relative;z-index:1}
      .actions{position:fixed;top:16px;right:16px;display:flex;gap:8px;z-index:10}
      .actions button{background:#3b82f6;color:white;border:none;padding:8px 16px;border-radius:8px;font-family:inherit;font-size:13px;font-weight:600;cursor:pointer;box-shadow:0 2px 8px rgba(59,130,246,.3)}
      .actions button:hover{background:#2563eb}
      @media print{.actions{display:none}.watermark{position:fixed}body{padding:32px;max-width:none}}
    </style></head><body>
      <div class="actions"><button onclick="window.print()">⬇ Download PDF</button></div>
      <div class="watermark">⚡ HustleAI</div>
      <div class="header">
        <span class="badge">🚀 7-Day Action Blueprint</span>
        <h1>${b.title}</h1>
        ${b.description ? `<div class="subtitle">${b.description}</div>` : ""}
        ${typeof b.actionScore === "number" && b.actionScore > 0 ? `<div class="score">🎯 Action Score: ${b.actionScore}%</div>` : ""}
      </div>
      <div class="content">${html}</div>
      <div class="footer">
        <p>Generated by <a href="https://hustlaiapp.in">HustleAI</a> — AI-Powered Side Hustle Discovery Platform</p>
        <p style="margin-top:4px;">© ${new Date().getFullYear()} HustleAI — hustlaiapp.in</p>
      </div>
    </body></html>`);
  win.document.close();
  if (autoPrint) setTimeout(() => win.print(), 800);
}